-- public.odds source

CREATE OR REPLACE VIEW odds
AS WITH total_prediction AS (
         SELECT m.id,
            count(*) AS total_predictions
           FROM matches m
             JOIN predictions p ON m.id = p.match_id
          GROUP BY m.id
        ), partial_prediction AS (
         SELECT m.id,
            p.prediction,
            count(*) AS partial_prediction
           FROM matches m
             JOIN predictions p ON m.id = p.match_id
          GROUP BY m.id, p.prediction
        )
 SELECT tp.id,
    pp.prediction,
    tp.total_predictions::double precision / pp.partial_prediction::double precision AS odd,
    tp.total_predictions,
    pp.partial_prediction
   FROM total_prediction tp
     JOIN partial_prediction pp ON tp.id = pp.id;

