GRANT ALL ON TABLE odd_standings TO neondb_owner;


-- public.standings source

CREATE OR REPLACE VIEW standings
AS SELECT m.matchday,
    p.user_id,
    count(*) AS points
   FROM matches m
     JOIN predictions p ON m.id = p.match_id AND m.winner::text = p.prediction::text
  GROUP BY p.user_id, m.matchday;

-- Permissions

ALTER TABLE standings OWNER TO neondb_owner;
GRANT ALL ON TABLE standings TO neondb_owner;

-- public.one_to_one_standings source

CREATE OR REPLACE VIEW one_to_one_standings
AS SELECT matchday,
    user_id,
    sum(( SELECT count(*) * 3
           FROM standings si
          WHERE s.points > si.points AND si.matchday = s.matchday)) + sum(( SELECT count(*) * 1
           FROM standings si
          WHERE s.points = si.points AND si.matchday = s.matchday AND si.user_id::text <> s.user_id::text)) AS points
   FROM standings s
  GROUP BY matchday, user_id;

