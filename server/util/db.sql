CREATE TABLE matches (
	id int8 GENERATED BY DEFAULT AS IDENTITY( MINVALUE 0 NO MAXVALUE START 0 NO CYCLE) NOT NULL,
	matchday int4 NOT NULL,
	start_date timestamp NOT NULL,
	status varchar(255) NULL,
	score_home int4 NULL,
	score_away int4 NULL,
	created_at timestamp NOT NULL,
	updated_at timestamp NOT NULL,
	home_team_id int8 NULL,
	away_team_id int8 NULL,
	referee varchar(255) NULL,
	score_halftime_home int4 NULL,
	score_halftime_away int4 NULL,
	winner varchar(1) NULL,
	external_id int8 NOT NULL,
	CONSTRAINT matches_pkey PRIMARY KEY (id)
);


